/**
 * Parser for anchor-nav-sticky. Base: anchor-nav (custom, no Block Collection equivalent).
 * Source: https://www.lenovo.com/us/en/c/laptops/thinkpad/ (.anchor_nav) — 1 instance
 * Output (1 column): one row per jump link -> <a href="#{heading-id}">{label}</a>
 *
 * Source: .anchor_nav__list > button.anchor_nav__text[data-anchorname="discover-thinkpad-scroll"].
 * The buttons are script-driven (no href). Each data-anchorname points at an empty marker
 * div[tag="anchor"].anchor-content-view-box[anchor-name=...] placed right before the target
 * section's heading. Those markers are empty spacers (removed by lenovo-laptops-cleanup.js
 * before parsers run), and on EDS the target is the heading's own id (github-slugger of the
 * heading text, generated by the pipeline). Target resolution, first hit wins:
 *   1. marker present -> first H1-H3 after it in document order
 *   2. markers gone   -> section headlines (.dx-big-section-headline) paired with the buttons by
 *                        position, only when both lists have the same length
 *   3. otherwise      -> a heading in main whose text contains every word of the button label
 * Links whose target cannot be resolved are omitted (never invented). "Reviews" is skipped
 * (section excluded from the migration).
 * Generated: 2026-10-15 (laptops template)
 */
const EXCLUDED_LABELS = ['reviews']; // excluded section (live Bazaarvoice feed)

function clean(text) {
  return (text || '').replace(/\s+/g, ' ').trim();
}

// github-slugger (used by the EDS pipeline for heading ids)
function slug(text) {
  return clean(text).toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-');
}

function words(text) {
  return clean(text).toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').split(/\s+/)
    .filter((w) => w.length > 2);
}

// First heading after the marker, provided it comes before the next marker and is page
// content (lazy-loaded sections may not be rendered yet: then nothing is returned).
function nextHeading(marker, document) {
  const scope = marker.closest('main') || document.body;
  const walker = document.createTreeWalker(scope, 1 /* SHOW_ELEMENT */);
  walker.currentNode = marker;
  let node = walker.nextNode();
  while (node) {
    if (node.hasAttribute('anchor-name')) return null;
    if (/^H[1-3]$/.test(node.tagName) && clean(node.textContent)) return node;
    node = walker.nextNode();
  }
  return null;
}

// Section headlines in document order; nested headline spans resolve to their heading.
function sectionHeadlines(document, nav) {
  const list = [];
  document.querySelectorAll('.dx-big-section-headline').forEach((el) => {
    const heading = el.closest('h1, h2, h3') || el;
    if (nav.contains(heading) || !clean(heading.textContent)) return;
    if (!/^H[1-3]$/.test(heading.tagName)) return;
    if (!list.includes(heading)) list.push(heading);
  });
  return list;
}

export default function parse(element, { document }) {
  const buttons = [...element.querySelectorAll('.anchor_nav__text, [data-anchorname]')]
    .filter((b, i, all) => all.indexOf(b) === i && clean(b.textContent));
  const items = buttons.map((b) => ({ label: clean(b.textContent), name: b.getAttribute('data-anchorname') || '' }));

  const headlines = sectionHeadlines(document, element);
  const main = element.closest('main') || document.body;
  const allHeadings = [...main.querySelectorAll('h1, h2, h3')]
    .filter((h) => !element.contains(h) && clean(h.textContent));

  const resolve = (item, index) => {
    // 1. marker element
    if (item.name) {
      const marker = [...document.querySelectorAll('[anchor-name]')]
        .find((m) => m.getAttribute('anchor-name') === item.name);
      if (marker) {
        const h = nextHeading(marker, document);
        if (h) return h;
      }
    }
    // 2. positional pairing with the section headlines
    if (headlines.length === items.length) return headlines[index];
    // 3. a page heading that contains every word of the label
    const labelWords = words(item.label);
    if (!labelWords.length) return null;
    return allHeadings.find((h) => {
      const hw = words(h.textContent);
      return labelWords.every((w) => hw.includes(w));
    }) || null;
  };

  const cells = [];
  const seen = new Set();
  items.forEach((item, index) => {
    if (EXCLUDED_LABELS.includes(item.label.toLowerCase())) return;
    const heading = resolve(item, index);
    if (!heading || EXCLUDED_LABELS.includes(clean(heading.textContent).toLowerCase())) return;
    const id = slug(heading.textContent);
    if (!id || seen.has(id)) return;
    seen.add(id);
    const a = document.createElement('a');
    a.href = `#${id}`;
    a.textContent = item.label;
    cells.push([a]);
  });

  if (!cells.length) {
    element.replaceWith(...element.childNodes);
    return;
  }

  const block = WebImporter.Blocks.createBlock(document, { name: 'anchor-nav-sticky', cells });
  element.replaceWith(block);
}
